public class basics{
    public static void main(String[]args){
        // operators in bit manipulation
        // &, |, >>, <<, 1~s complement

        System.out.println(4&5);
        System.out.println(4|5);
        System.out.println(10<<2);
        System.out.println(10>>2);
        System.out.println(~5);


    }
}